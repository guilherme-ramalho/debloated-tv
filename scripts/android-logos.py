#!/usr/bin/env python3
"""Converts the iPhone app's streaming logos (ios/Assets.xcassets/*Logo.imageset/*.svg) into Android vector
drawables (android/app/src/main/res/drawable/logo_*.xml), white, to be tinted like the iPhone's template images.
Handles the shapes these files use: <path> and <polygon>; an embedded PNG (Disney+) is written as a PNG."""
import base64, pathlib, re, xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ios/Assets.xcassets"
OUT = ROOT / "android/app/src/main/res"
NS = "{http://www.w3.org/2000/svg}"

def name_for(imageset: str) -> str:
    return "logo_" + re.sub(r"Logo$", "", imageset).lower().replace("+", "plus")

for svg in sorted(SRC.glob("*Logo.imageset/*.svg")):
    name = name_for(svg.parent.stem)
    root = ET.parse(svg).getroot()
    x, y, w, h = (float(v) for v in root.get("viewBox").replace(",", " ").split())
    images = [e for e in root.iter() if e.tag == NS + "image"]
    if images:
        href = images[0].get("{http://www.w3.org/1999/xlink}href") or images[0].get("href")
        data = base64.b64decode(href.split(",", 1)[1])
        (OUT / "drawable-nodpi").mkdir(parents=True, exist_ok=True)
        (OUT / "drawable-nodpi" / f"{name}.png").write_bytes(data)
        print(f"{name}.png (embedded image)")
        continue
    paths = []
    for e in root.iter():
        if e.tag == NS + "path":
            paths.append((e.get("d"), e.get("fill-rule") == "evenodd"))
        elif e.tag == NS + "polygon":
            pts = e.get("points").replace(",", " ").split()
            pairs = [f"{pts[i]},{pts[i+1]}" for i in range(0, len(pts), 2)]
            paths.append(("M" + " L".join(pairs) + "Z", False))
    even = ' android:fillType="evenOdd"'
    body = "\n".join(
        f'        <path android:fillColor="#FFFFFFFF"{even if odd else ""} android:pathData="{d}" />'
        for d, odd in paths)
    width = 24 * w / h
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-logos.py from ios/Assets.xcassets/{svg.parent.name}/{svg.name}; don't edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width:.2f}dp" android:height="24dp"
    android:viewportWidth="{w}" android:viewportHeight="{h}">
    <group android:translateX="{-x}" android:translateY="{-y}">
{body}
    </group>
</vector>
'''
    (OUT / "drawable" / f"{name}.xml").write_text(xml)
    print(f"{name}.xml ({len(paths)} paths)")
